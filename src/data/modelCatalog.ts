/** Resource-hex frequency plus the four Port numbers. There is no 7. */
export function numberChipCopies(n: number): number {
  return (NUMBER_DISTRIBUTION[n] ?? 0) + PORT_NUMBERS.filter((p) => p === n).length;
}

export const NUMBER_CHIP_VALUES = [3, 4, 5, 6, 8, 9, 10, 11] as const;
export const NUMBER_CHIP_TOTAL = NUMBER_CHIP_VALUES.reduce((sum, n) => sum + numberChipCopies(n), 0);

const SETTINGS = 'PLA or PETG · 0.4 mm nozzle · 0.2 mm layers · 2–3 perimeters';
const FINE = 'PLA · 0.4 mm nozzle (0.2 mm nozzle optional) · 0.12 mm layers for the numeral or silhouette';

function chip(n: number): PrintModel {
  return {
    id: `number_chip_${n}`,
    name: `Number chip ${n}`,
    category: 'Number Chips',
    summary: 'Raised numeral on an ivory disc. The same model generates every value; only the digit geometry changes. No chip is numbered 7.',
    copies: numberChipCopies(n),
    quantityNote: 'Count is the approved number-token distribution, including the four Port numbers.',
    material: 'PLA, ivory body. A second colour is optional paint or a filament change, not a second file.',
    filament: 'ivory',
    orientation: 'Face up, on the disc.',
    supports: 'None.',
    settings: FINE,
    bundle: 'currency-and-tokens',
  };
}

